import type { MeshPoint, GlobalEngineSettings, ExportOptions, MeshGradientDocument } from '../types/mesh';
import { WebGLMeshRenderer } from './webgl-renderer';

export interface RenderExportResult {
  blob: Blob;
  dataUrl: string;
  width: number;
  height: number;
}

// Render offscreen canvas with WebGL at target resolution
export async function renderOffscreenCanvas(
  points: MeshPoint[],
  settings: GlobalEngineSettings,
  targetWidth: number,
  targetHeight: number
): Promise<HTMLCanvasElement> {
  const offscreenCanvas = document.createElement('canvas');
  offscreenCanvas.width = targetWidth;
  offscreenCanvas.height = targetHeight;

  const renderer = new WebGLMeshRenderer(offscreenCanvas);
  renderer.render(points, settings, targetWidth, targetHeight);

  return offscreenCanvas;
}

// Export as PNG or JPEG Blob
export async function exportImage(
  points: MeshPoint[],
  settings: GlobalEngineSettings,
  docWidth: number,
  docHeight: number,
  options: ExportOptions
): Promise<RenderExportResult> {
  const targetWidth = Math.round(docWidth * options.scale);
  const targetHeight = Math.round(docHeight * options.scale);

  // Safety checks for memory/resolution
  if (targetWidth > 8192 || targetHeight > 8192) {
    throw new Error(`Dimensão de exportação (${targetWidth}x${targetHeight}) excede o limite de segurança de 8192px.`);
  }

  // Adjust settings for JPEG: cannot have transparency
  const renderSettings: GlobalEngineSettings = {
    ...settings,
    transparentBackground: options.format === 'jpeg' ? false : settings.transparentBackground,
    backgroundColor: options.format === 'jpeg' ? options.backgroundColor : settings.backgroundColor,
  };

  const canvas = await renderOffscreenCanvas(points, renderSettings, targetWidth, targetHeight);

  let mimeType = 'image/png';
  let quality: number | undefined = undefined;

  if (options.format === 'jpeg') {
    mimeType = 'image/jpeg';
    quality = Math.max(0.1, Math.min(1.0, options.quality));
  }

  return new Promise((resolve, reject) => {
    canvas.toBlob(
      (blob) => {
        if (!blob) {
          reject(new Error('Falha ao gerar imagem a partir do canvas.'));
          return;
        }
        const dataUrl = URL.createObjectURL(blob);
        resolve({
          blob,
          dataUrl,
          width: targetWidth,
          height: targetHeight,
        });
      },
      mimeType,
      quality
    );
  });
}

// Export as SVG with vector dimensions, metadata, and embedded lossless raster
export async function exportSvg(
  points: MeshPoint[],
  settings: GlobalEngineSettings,
  docWidth: number,
  docHeight: number,
  options: ExportOptions
): Promise<{ svgString: string; blob: Blob; dataUrl: string }> {
  const targetWidth = Math.round(docWidth * options.scale);
  const targetHeight = Math.round(docHeight * options.scale);

  const canvas = await renderOffscreenCanvas(points, settings, targetWidth, targetHeight);
  const dataUrl = canvas.toDataURL('image/png');

  // Vector metadata comments so vector editors/developers can inspect point coordinates
  const pointsMeta = points
    .map(
      (p, i) =>
        `    <!-- Point ${i + 1}: pos=(${Math.round(p.x * docWidth)}, ${Math.round(p.y * docHeight)}) color=${p.color} radius=${p.radius} intensity=${p.intensity} -->`
    )
    .join('\n');

  const svgContent = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by Mesh Gradient Studio -->
<!-- Visual Technique: Organic IDW/RBF Multi-point Shader Interpolation -->
<svg xmlns="http://www.w3.org/2000/svg" 
     xmlns:xlink="http://www.w3.org/1999/xlink" 
     width="${docWidth}" 
     height="${docHeight}" 
     viewBox="0 0 ${docWidth} ${docHeight}">
  <metadata>
    <mesh-gradient-studio:project>
      <mesh-gradient-studio:points count="${points.length}">
${pointsMeta}
      </mesh-gradient-studio:points>
    </mesh-gradient-studio:project>
  </metadata>
  <defs>
    <!-- Note: Organic multi-point smooth non-linear interpolation is preserved via high-fidelity embedded raster -->
  </defs>
  <image width="${docWidth}" height="${docHeight}" preserveAspectRatio="none" xlink:href="${dataUrl}"/>
</svg>`;

  const blob = new Blob([svgContent], { type: 'image/svg+xml;charset=utf-8' });
  const objectUrl = URL.createObjectURL(blob);

  return {
    svgString: svgContent,
    blob,
    dataUrl: objectUrl,
  };
}

// Copy rendered image directly to Clipboard
export async function copyImageToClipboard(
  points: MeshPoint[],
  settings: GlobalEngineSettings,
  docWidth: number,
  docHeight: number
): Promise<void> {
  if (!navigator.clipboard || !navigator.clipboard.write) {
    throw new Error('A API de Área de Transferência não é suportada neste navegador.');
  }

  const canvas = await renderOffscreenCanvas(points, settings, docWidth, docHeight);

  return new Promise((resolve, reject) => {
    canvas.toBlob(async (blob) => {
      if (!blob) {
        reject(new Error('Não foi possível gerar blob de imagem.'));
        return;
      }
      try {
        const item = new ClipboardItem({ 'image/png': blob });
        await navigator.clipboard.write([item]);
        resolve();
      } catch (err) {
        reject(err);
      }
    }, 'image/png');
  });
}

// Download blob trigger
export function triggerDownload(url: string, filename: string) {
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
}

// JSON Project serialization & validation
export function exportProjectJson(doc: MeshGradientDocument): string {
  return JSON.stringify(doc, null, 2);
}

export function validateAndParseProjectJson(jsonStr: string): MeshGradientDocument {
  let parsed: unknown;
  try {
    parsed = JSON.parse(jsonStr);
  } catch {
    throw new Error('O arquivo selecionado não contém um JSON válido.');
  }

  if (typeof parsed !== 'object' || parsed === null) {
    throw new Error('Formato de projeto inválido.');
  }

  const doc = parsed as Partial<MeshGradientDocument>;

  if (!Array.isArray(doc.points) || doc.points.length === 0) {
    throw new Error('O projeto deve conter pelo menos um ponto de malha.');
  }

  if (!doc.dimensions || typeof doc.dimensions.width !== 'number' || typeof doc.dimensions.height !== 'number') {
    throw new Error('Dimensões do projeto inválidas.');
  }

  // Validate and normalize points
  const normalizedPoints: MeshPoint[] = doc.points.map((p, idx) => ({
    id: p.id || `pt-${Date.now()}-${idx}`,
    x: Math.max(0, Math.min(1, typeof p.x === 'number' ? p.x : 0.5)),
    y: Math.max(0, Math.min(1, typeof p.y === 'number' ? p.y : 0.5)),
    color: typeof p.color === 'string' && p.color.startsWith('#') ? p.color : '#888888',
    alpha: typeof p.alpha === 'number' ? Math.max(0, Math.min(1, p.alpha)) : 1,
    radius: typeof p.radius === 'number' ? Math.max(0.1, Math.min(5, p.radius)) : 1.0,
    intensity: typeof p.intensity === 'number' ? Math.max(0.1, Math.min(5, p.intensity)) : 1.0,
    locked: Boolean(p.locked),
  }));

  const normalizedSettings: GlobalEngineSettings = {
    smoothness: doc.settings?.smoothness ?? 2.2,
    colorSpace: doc.settings?.colorSpace ?? 'oklab',
    contrast: doc.settings?.contrast ?? 1.0,
    saturation: doc.settings?.saturation ?? 1.0,
    brightness: doc.settings?.brightness ?? 1.0,
    hueShift: doc.settings?.hueShift ?? 0,
    noiseIntensity: doc.settings?.noiseIntensity ?? 0.0,
    noiseScale: doc.settings?.noiseScale ?? 1.5,
    vignetteIntensity: doc.settings?.vignetteIntensity ?? 0.0,
    vignetteRadius: doc.settings?.vignetteRadius ?? 0.8,
    backgroundColor: doc.settings?.backgroundColor ?? '#000000',
    transparentBackground: Boolean(doc.settings?.transparentBackground),
    seed: doc.settings?.seed ?? 42,
  };

  return {
    id: doc.id || `project-${Date.now()}`,
    name: doc.name || 'Projeto Sem Nome',
    version: doc.version || '1.0.0',
    createdAt: doc.createdAt || Date.now(),
    updatedAt: Date.now(),
    dimensions: {
      width: Math.max(64, Math.min(8192, Math.round(doc.dimensions.width))),
      height: Math.max(64, Math.min(8192, Math.round(doc.dimensions.height))),
      lockAspectRatio: Boolean(doc.dimensions.lockAspectRatio),
      presetName: doc.dimensions.presetName,
    },
    points: normalizedPoints,
    settings: normalizedSettings,
    presetOrigin: doc.presetOrigin,
  };
}
